export function getDailyRef(date = new Date()): Ref {
  const start = new Date(date.getFullYear(), 0, 0);
  const day = Math.floor((date.getTime() - start.getTime()) / 86_400_000);
  return dailyRefs[day % dailyRefs.length];
}
